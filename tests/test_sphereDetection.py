"""
Tests of the calibration sphere detection: automatic detection against the ground truth, parity of all the modes
with aliceVision_sphereDetection.
"""

import json
import os
import shutil

import pytest
from pyalicevision import sfmDataIO

from conftest import MODEL
from makeSyntheticDataset import runCommand

from photometricStereoHalide import dataIO, sphereDetection

def observations(path):
    with open(path) as f:
        return json.load(f)["shapes"][0]["observations"] or {}


def assertSameObservations(observationsA, observationsB, tolerance):
    """ Compare 2 sets of observations, whose values may be numbers or strings (AliceVision writes strings). """
    assert set(observationsA) == set(observationsB)
    for viewId, a in observationsA.items():
        b = observationsB[viewId]
        values = [(a["center"]["x"], b["center"]["x"]), (a["center"]["y"], b["center"]["y"]), (a["radius"], b["radius"])]
        if "score" in a or "score" in b:
            values.append((a["score"], b["score"]))
        for valueA, valueB in values:
            assert float(valueA) == pytest.approx(float(valueB), abs=tolerance), viewId


def viewsPerPose(dataset):
    """ Return {pose name: [non-ambient view ids]}. """
    sfm = dataIO.loadSfmData(dataset.sfmPath)
    poseNames = {poseId: name for name, poseId in dataset.poseIds.items()}
    views = {}
    for viewId, view in sfm.getViews().items():
        if not dataIO.isAmbient(view.getImage().getImagePath()):
            views.setdefault(poseNames[view.getPoseId()], []).append(str(viewId))
    return views


def runAliceVisionSphereDetection(dataset, outputPath, *args):
    if not shutil.which("aliceVision_sphereDetection"):
        pytest.skip("aliceVision_sphereDetection is not available.")
    runCommand(["aliceVision_sphereDetection", "--input", dataset.sfmPath, "--modelPath", os.path.expandvars(MODEL),
                "--output", str(outputPath), "--verboseLevel", "error", *args])
    return str(outputPath)


def test_autoDetectionGroundTruth(dataset, autoDetection):
    detected = observations(autoDetection)
    for name, viewIds in viewsPerPose(dataset).items():
        cx, cy, radius = dataset.spheres[name]
        for viewId in viewIds:
            # Every lit image has a detection: the ambient images are skipped
            observation = detected.pop(viewId)
            assert observation["type"] == "matte"
            assert 0 < observation["score"] <= 1
            # The network boxes only the lit part of the sphere: the error increases with the light angle
            assert abs(observation["center"]["x"] - cx) < 0.3 * radius
            assert abs(observation["center"]["y"] - cy) < 0.3 * radius
            assert abs(observation["radius"] - radius) < 0.3 * radius
    assert not detected


def test_autoDetectionMinScore(dataset, modelAvailable, tmp_path):
    # Single view SfMData, for speed
    sfm = dataIO.loadSfmData(dataset.sfmPath)
    views = sfm.getViews()
    for viewId in list(views.keys())[1:]:
        views.erase(viewId)
    sfmPath = str(tmp_path / "oneView.sfm")
    assert sfmDataIO.save(sfm, sfmPath, sfmDataIO.VIEWS | sfmDataIO.INTRINSICS)

    outputPath = tmp_path / "detection.json"
    sphereDetection.autoDetectSpheres(sfmPath, MODEL, str(outputPath), minScore=1.0)
    assert observations(outputPath) == {}


def test_missingModel(dataset, tmp_path):
    with pytest.raises(FileNotFoundError):
        sphereDetection.autoDetectSpheres(dataset.sfmPath, str(tmp_path / "missing.onnx"), str(tmp_path / "out.json"))


def test_autoDetectionParity(dataset, autoDetection, tmp_path):
    expected = runAliceVisionSphereDetection(dataset, tmp_path / "aliceVision.json", "--autoDetect", "1")
    assertSameObservations(observations(autoDetection), observations(expected), tolerance=1e-3)


def manualSpheres(dataset):
    """ Spheres of a few views of pose A. The ids have the same number of digits: the last one is the same in
    numeric (Python) and lexicographic (C++) orders. """
    viewIds = sorted(viewsPerPose(dataset)["A"], key=int)
    viewIds = [v for v in viewIds if len(v) == len(viewIds[-1])][-3:]
    cx, cy, radius = dataset.spheres["A"]
    return {viewId: {"center": {"x": cx + i, "y": cy - i}, "radius": radius + 0.5 * i} for i, viewId in enumerate(viewIds)}


@pytest.mark.parametrize("fillMissingSpheres", [False, True])
def test_manualSpheresParity(dataset, tmp_path, fillMissingSpheres):
    spheres = manualSpheres(dataset)
    outputPath = tmp_path / "detection.json"
    sphereDetection.writeManualSpheres(dataset.sfmPath, spheres, str(outputPath), fillMissingSpheres)
    result = observations(outputPath)
    assert len(result) == (len(dataIO.loadSfmData(dataset.sfmPath).getViews()) if fillMissingSpheres else len(spheres))

    # Keyable values on the command line, as generated by Meshroom: '{"<viewId>": value, ...}' split by the shell
    def keyableArg(name, values):
        tokens = " ".join(f"{k}: {v}," for k, v in values.items()).rstrip(",")
        return [f"--{name}", *("{" + tokens + "}").split()]

    expected = runAliceVisionSphereDetection(
        dataset, tmp_path / "aliceVision.json", "--autoDetect", "0", "--fillMissingSpheres", str(int(fillMissingSpheres)),
        *keyableArg("x", {k: v["center"]["x"] for k, v in spheres.items()}),
        *keyableArg("y", {k: v["center"]["y"] for k, v in spheres.items()}),
        *keyableArg("radius", {k: v["radius"] for k, v in spheres.items()}))
    assertSameObservations(result, observations(expected), tolerance=1e-3)


def test_manualSpheresIgnoreUndefined(dataset, tmp_path):
    spheres = manualSpheres(dataset)
    undefinedViewId = next(iter(spheres))
    spheres[undefinedViewId]["radius"] = -1.0
    outputPath = tmp_path / "detection.json"
    sphereDetection.writeManualSpheres(dataset.sfmPath, spheres, str(outputPath), fillMissingSpheres=False)
    assert set(observations(outputPath)) == set(spheres) - {undefinedViewId}


@pytest.mark.parametrize("fillMissingSpheres", [False, True])
def test_sphereFileParity(dataset, tmp_path, fillMissingSpheres):
    # Sphere file with the spheres of pose A only
    with open(dataset.spheresPath) as f:
        sphereFile = json.load(f)
    viewIdsA = set(viewsPerPose(dataset)["A"])
    shape = sphereFile["shapes"][0]
    shape["observations"] = {k: v for k, v in shape["observations"].items() if k in viewIdsA}
    sphereFilePath = tmp_path / "spheres.json"
    sphereFilePath.write_text(json.dumps(sphereFile, indent=4))

    outputPath = tmp_path / "detection.json"
    sphereDetection.writeSpheresFromFile(dataset.sfmPath, str(sphereFilePath), str(outputPath), fillMissingSpheres)
    if not fillMissingSpheres:
        assert outputPath.read_text() == sphereFilePath.read_text()

    expected = runAliceVisionSphereDetection(
        dataset, tmp_path / "aliceVision.json", "--autoDetect", "0", "--sphereFile", str(sphereFilePath),
        "--fillMissingSpheres", str(int(fillMissingSpheres)))
    assertSameObservations(observations(outputPath), observations(expected), tolerance=1e-3)

